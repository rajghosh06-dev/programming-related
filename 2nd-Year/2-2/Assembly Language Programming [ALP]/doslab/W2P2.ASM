;PROGRAM TO DISPLAY MULTIPLE STRINGS LINE BY LINE
ASSUME CS:CODE, DS:DATA ;ASSUME IS AN ASSEMBLER DIRECTIVE TO DECLARE SEGMENTS
DATA SEGMENT
        STR1 DB "COMPUTER SCIENCE AND ENGINEERING",13,10,"GEETHANJALI",0DH,0AH,"AIML$"
                        ;DISPLAYING MULTIPLE STRINGS IN NEW LINE
DATA ENDS
CODE SEGMENT
        MOV AX, DATA    ;READING ADDRESS OF DATA SEGMENT AND MOVING TO AX
        MOV DS, AX      ;MOVING CONTENTS OF AX TO DS
        MOV DX, OFFSET STR1; READING OFFSET ADDRESS OF STR1

        MOV AH, 09H     ;DOS INT 21H SERVICE: DISPLAY STRING
        INT 21H         ;THE TWO INSTRUCTION TOGETHER CONSIDERED UNDER ISR-09
                        ;INTERRUPT SERVICE ROUTINE-09 : TO DISPLAY STRING OF CHARACTERS

        MOV AH, 4CH     ;DOS INT 21H SERVICE: TERMINATE WITH RETURN CODE
        INT 21H         ;THE TWO INSTRUCTIONS TOGETHER CONSIDERED AS UNDER ISR-4C
                        ;INTERRUPT SERVICE ROUTINE-4C : TO TERMINATE WITH RETURN CODE
CODE ENDS
END                     ;END OF PROGRAM
