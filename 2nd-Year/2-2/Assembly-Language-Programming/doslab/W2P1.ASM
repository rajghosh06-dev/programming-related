; PROGRAM TO DISPLAY STRING "COMPUTER SCIENCE AND ENGINEERING" FOR 8086
ASSUME CS:CODE, DS:DATA ;ASSUME IS AN ASSEMBLER DIRECTIVE TO DECLARE SEGMENTS
DATA SEGMENT
        STR1 DB "COMPUTER SCIENCE AND ENGINEERING$"  ;SINGLE QUOTES ALSO SUPPORTED
DATA ENDS

CODE SEGMENT
        MOV AX, DATA    ;READING ADDRESS OF DATA SEGMENT AND MOVING TO AX
        MOV DS, AX      ;MOVING CONTENTS OF AX TO DS

        MOV DX, OFFSET STR1 ;READING OFFSET ADDRESS TO STR1
        MOV AH, 09H     ;DOS INT 21H SERVICE: DISPLAY STRING

        INT 21H         ;THE TWO INSTRUCTION TOGETHER CONSIDERED UNDER ISR-09
                        ;INTERRUPT SERVICE ROUTINE 09
        HLT             ;HALT
CODE ENDS
END                     ;END OF PROGRAM
