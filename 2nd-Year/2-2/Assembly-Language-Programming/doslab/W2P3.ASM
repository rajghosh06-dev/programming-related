; PROGRAM TO FIND MAXIMUM OF THREE NUMBERS
ASSUME CS:CODE, DS:DATA
DATA SEGMENT
        ARR DB 13H, 56H, 67H, 08H, 0A5H
DATA ENDS
CODE SEGMENT
        MOV AX, DATA
        MOV DS, AX
        MOV SI, OFFSET ARR      ;USING DIRECTIVE
                                ;ALTERNATIVE USING : LEA SI, ARR
        MOV CL, 04H             ;NO. OF COMPARISION(N-1): N: NUMBER OF ELEMENTS
        MOV AL, [SI]            ;LOADING THE FIRST ELEMENT OF [SI]
        INC SI                  ;INCREMENTING THE SI TO NEXT ELEMENT

        BACK: MOV BL,[SI]       ;MOVING THE ELEMENT OF [SI] INTO BL
        CMP AL, BL              ;COMPARING AL AND BL ELEMENTS

        JA GO                   ;JA-> JUMP IF ABOVE USED FOR UNUSED FOR UNSIGNED NUMBERS
                                ;JG-> JUMP IF GREATER USED FOR SIGNED NUMBERS
        XCHG AL, BL             ;IF AL<BL EXCHANGE THE CONTENT SUCH THAT AL IS ALWAYS BIGGER NUMBER
        GO: INC SI              ;INCREMENT THE POSITION TO THE NEXT ELEMENT
        DEC CL                  ;DECREMENT COUNTER
        JNZ BACK                ;IF CL!=0 REPEAT INTO MEMORY
        MOV [SI],AL             ;STORING THE RESULT INTO MEMORY
        INT 03H                 ;SIGNIFIES BREAKPOINT, HALTING PROBLEM EXECUTION AND TRANSFER
                                ;CONTROL TO THE DEBUGGER
CODE ENDS
END
