ASSUME CS:CODE, DS:DATA
DATA SEGMENT
    ARR DB 12H,13H,05H,35H,46H,76H
    COU DB 06H
    MAX DB ?
    MIN DB ?
DATA ENDS

CODE SEGMENT
    MOV AX,DATA
    MOV DS,AX
    MOV SI,OFFSET ARR
    MOV CL,COU
    MOV AL,[SI]
    MOV MIN,AL 
    MOV MAX,AL

BACK: INC SI
    MOV AL,[SI]
    CMP MIN,AL
    JL CHMAX
    MOV MIN,AL

CHMAX: CMP MAX,AL
    JG GO
    MOV MAX,AL

GO: DEC CL
    JNZ BACK

    HLT
CODE ENDS
END

